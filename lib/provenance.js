/* Provenance: what the file itself declares about where it came from.

   This is the only check here that is deterministic. It reads bytes, calls
   nothing, and either finds a marker or does not. When it finds one that is
   evidence. When it finds nothing that is not evidence of anything, because
   almost every upload pipeline strips metadata on the way through.

   It does NOT verify C2PA signatures cryptographically. It reports that a
   manifest is present, which is a different and weaker claim. */

import zlib from 'node:zlib';

/* Markers that identify a generator or a provenance standard. Matched as plain
   ASCII against the raw bytes, so they are caught in EXIF, XMP, JUMBF, MP4
   boxes and PNG chunks alike without a parser for each. */
const MARKERS = [
  ['c2pa', 'C2PA Content Credentials', 'provenance'],
  ['jumbf', 'JUMBF provenance container', 'provenance'],
  ['contentcredentials', 'Content Credentials', 'provenance'],
  ['trainedAlgorithmicMedia', 'IPTC: generated by a trained algorithm', 'declared-ai'],
  ['compositeWithTrainedAlgorithmicMedia', 'IPTC: composited with AI material', 'declared-ai'],
  ['digitalSourceType', 'IPTC digital source type', 'declared-ai'],
  ['stable diffusion', 'Stable Diffusion', 'generator'],
  ['stablediffusion', 'Stable Diffusion', 'generator'],
  ['automatic1111', 'AUTOMATIC1111 WebUI', 'generator'],
  ['comfyui', 'ComfyUI', 'generator'],
  ['midjourney', 'Midjourney', 'generator'],
  ['dall-e', 'DALL-E', 'generator'],
  ['openai', 'OpenAI', 'generator'],
  ['firefly', 'Adobe Firefly', 'generator'],
  ['imagen', 'Google Imagen', 'generator'],
  ['sora', 'Sora', 'generator'],
  ['runway', 'Runway', 'generator'],
  ['leonardo.ai', 'Leonardo.Ai', 'generator'],
  ['flux', 'FLUX', 'generator'],
  ['nano banana', 'Nano Banana', 'generator'],
  ['veo', 'Google Veo', 'generator'],
  ['synthid', 'Google SynthID', 'provenance'],
  ['adobe photoshop', 'Adobe Photoshop', 'editor'],
  ['gimp', 'GIMP', 'editor'],
  ['canva', 'Canva', 'editor'],
  ['figma', 'Figma', 'editor'],
];

/* PNG text chunks are where image generators write their prompts, so they are
   worth parsing properly rather than scanning for. */
function pngChunks(buf) {
  const out = [];
  if (buf.length < 8 || buf[0] !== 0x89 || buf.slice(1, 4).toString('latin1') !== 'PNG') return out;
  let p = 8;
  while (p + 8 <= buf.length && out.length < 20) {
    const len = buf.readUInt32BE(p);
    const type = buf.slice(p + 4, p + 8).toString('latin1');
    const data = buf.slice(p + 8, p + 8 + len);
    if (len > buf.length) break;
    try {
      if (type === 'tEXt') {
        const i = data.indexOf(0);
        out.push({ key: data.slice(0, i).toString('latin1'), value: data.slice(i + 1).toString('latin1') });
      } else if (type === 'zTXt') {
        const i = data.indexOf(0);
        out.push({
          key: data.slice(0, i).toString('latin1'),
          value: zlib.inflateSync(data.slice(i + 2)).toString('utf8'),
        });
      } else if (type === 'iTXt') {
        const i = data.indexOf(0);
        const key = data.slice(0, i).toString('latin1');
        const compressed = data[i + 1] === 1;
        let q = i + 3;
        q = data.indexOf(0, q) + 1;   /* language tag */
        q = data.indexOf(0, q) + 1;   /* translated keyword */
        const rest = data.slice(q);
        out.push({ key, value: compressed ? zlib.inflateSync(rest).toString('utf8') : rest.toString('utf8') });
      }
    } catch { /* a malformed chunk is not worth failing the run over */ }
    if (type === 'IEND') break;
    p += 12 + len;
  }
  return out;
}

export function provenance(buf, mime, name) {
  if (!buf || !buf.length) {
    return { checked: false, verdict: 'not applicable', findings: [], note: 'Nothing to inspect: the input was text, not a file.' };
  }

  const findings = [];

  for (const c of pngChunks(buf)) {
    const v = String(c.value || '').trim();
    if (!v) continue;
    const isPrompt = /^(parameters|prompt|workflow|sd-metadata|dream)$/i.test(c.key);
    findings.push({
      kind: isPrompt ? 'generator' : 'metadata',
      what: 'PNG text chunk "' + c.key + '"',
      detail: v.slice(0, 400) + (v.length > 400 ? '…' : ''),
    });
  }

  /* Metadata clusters at the head and tail of a file, so scanning those windows
     catches it without walking a 20 MB video end to end. */
  const window = 262144;
  const hay = (buf.slice(0, window).toString('latin1')
    + '\u0000' + buf.slice(Math.max(0, buf.length - window)).toString('latin1')).toLowerCase();

  const seen = new Set();
  for (const [needle, label, kind] of MARKERS) {
    if (hay.includes(needle) && !seen.has(label)) {
      seen.add(label);
      findings.push({ kind, what: label, detail: 'Found as a marker in the file metadata.' });
    }
  }

  const has = k => findings.some(f => f.kind === k);
  const verdict = has('provenance') ? 'signed provenance present'
    : has('declared-ai') || has('generator') ? 'generator metadata present'
      : has('editor') ? 'editing software recorded'
        : 'nothing found';

  const note = verdict === 'nothing found'
    ? 'No provenance or generator metadata. This proves nothing: almost every social platform strips metadata on upload, so real and synthetic files both arrive bare.'
    : verdict === 'signed provenance present'
      ? 'A provenance manifest is embedded. This service reports its presence only. It does not check the cryptographic signature, so treat it as a lead and verify at contentcredentials.org.'
      : 'Metadata naming a tool was left in the file. It says what touched the file, not whether the content is true.';

  return { checked: true, verdict, findings: findings.slice(0, 12), note, mime, name };
}
